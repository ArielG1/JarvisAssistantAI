# Generate valid 1x1 white PNG then wrap in ICO
$png = [byte[]]@(
  0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,  # PNG signature
  # IHDR chunk
  0x00, 0x00, 0x00, 0x0D,  # length = 13
  0x49, 0x48, 0x44, 0x52,  # "IHDR"
  0x00, 0x00, 0x00, 0x01,  # width = 1
  0x00, 0x00, 0x00, 0x01,  # height = 1
  0x08, 0x02,              # bit depth = 8, color type = 2 (RGB)
  0x00, 0x00, 0x00,        # compression, filter, interlace
  0x90, 0x77, 0x53, 0xDE,  # CRC for IHDR
  # IDAT chunk (deflated: row filter=0, pixel=0xFFFFFF)
  0x00, 0x00, 0x00, 0x0C,  # length = 12
  0x49, 0x44, 0x41, 0x54,  # "IDAT"
  0x08, 0xD7, 0x63, 0xF8, 0xCF, 0xC0, 0x00, 0x00,
  0x00, 0x02, 0x00, 0x01,  # zlib compressed data
  0xE2, 0x21, 0xBC, 0x33,  # CRC for IDAT
  # IEND chunk
  0x00, 0x00, 0x00, 0x00,  # length = 0
  0x49, 0x45, 0x4E, 0x44,  # "IEND"
  0xAE, 0x42, 0x60, 0x82   # CRC for IEND
)

# ICO header + dir entry + PNG
$icoSize = 22 + $png.Length
$ico = New-Object byte[] $icoSize
# Header
$ico[2] = 1; $ico[4] = 1
# Dir entry
[System.BitConverter]::GetBytes([int]$png.Length).CopyTo($ico, 14)
[System.BitConverter]::GetBytes([int]22).CopyTo($ico, 18)
$png.CopyTo($ico, 22)

[System.IO.File]::WriteAllBytes("D:\Proyectos\Jarvis\src-tauri\icons\icon.ico", $ico)
Write-Output "icon.ico: $($ico.Length) bytes"
